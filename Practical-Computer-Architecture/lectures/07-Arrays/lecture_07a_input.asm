# ============================================================
# 07a: إدخال الأرقام في مصفوفة
# ============================================================
#
# ✨ المصفوفة = مجموعة متغيرات في RAM بجانب بعض
#    arr[0] عند عنوان base + 0
#    arr[1] عند عنوان base + 4
#    arr[i] عند عنوان base + i×4
#
#    sll: i × 4  (لأن int = 4 بايت)
#    sw:  خزّن في المصفوفة
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    arr:    .space 20        # 20 بايت = 5 أعداد × 4 بايت
                              # ← C++: int arr[5];

    prompt: .asciiz "Enter number: "

.text
main:
    la $s0, arr              # $s0 = عنوان أول عنصر في المصفوفة
                              # $s0 يشير إلى arr[0]

    li $t0, 0                # $t0 = i = 0 (العداد)

input_loop:
    # ------------------------------
    # شرط: i < 5 ?
    # ------------------------------
    bge $t0, 5, done         # if i >= 5 → اخرج من الحلقة

    # ------------------------------
    # اسأل المستخدم: أدخل رقماً
    # ------------------------------
    la $a0, prompt
    li $v0, 4
    syscall

    li $v0, 5
    syscall                  # $v0 = الرقم المدخل

    # ------------------------------
    # arr[i] = v0
    #   1) احسب: i × 4
    #   2) اجمع: base + (i × 4)
    #   3) خزّن: sw
    # ------------------------------
    sll $t1, $t0, 2          # $t1 = i × 4   (sll = ضرب × 4)
    add $t1, $s0, $t1        # $t1 = base + (i × 4) = عنوان arr[i]
    sw $v0, 0($t1)           # arr[i] = $v0

    addi $t0, $t0, 1         # i++
    b input_loop

done:
    li $v0, 10
    syscall
