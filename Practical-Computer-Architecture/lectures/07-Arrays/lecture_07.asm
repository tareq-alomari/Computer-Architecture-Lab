# ============================================================
# 07: المصفوفات — الوصول إلى arr[i]
# ============================================================
#
# ✨ المصفوفة: مجموعة متغيرات في RAM بجانب بعض
#    arr[0] عند base + 0
#    arr[1] عند base + 4
#    arr[i] عند base + i×4
#
# للنسخ المبسّطة، راجع:
#   lecture_07a_input.asm  ← إدخال فقط
#   lecture_07b_sum.asm    ← مجموع فقط
#
# أوامر جديدة:
#   .space n          → احجز n بايت في RAM
#   sll $t, $s, 2     → $t = $s × 4
#   sw $v, offset($b) → اكتب في RAM
#   lw $v, offset($b) → اقرأ من RAM
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    arr:    .space 20            # 20 بايت = 5 أعداد × 4 بايت
                                  # ← C++: int arr[5];
    prompt: .asciiz "Enter number: "
    sum_msg: .asciiz "Sum = "
    newline: .asciiz "\n"

.text
main:
    la $s0, arr                  # $s0 = base (عنوان أول عنصر)
    li $t0, 0                    # $t0 = i = 0
    li $t2, 0                    # $t2 = sum = 0

    # ========================================
    # حلقة الإدخال: اقرأ 5 أرقام
    # ========================================
input_loop:
    bge $t0, 5, sum_done         # if i >= 5 → اخرج

    la $a0, prompt
    li $v0, 4
    syscall

    li $v0, 5
    syscall                      # $v0 = الرقم المدخل

    # --- arr[i] = v0 ---
    sll $t1, $t0, 2              # $t1 = i × 4
    add $t1, $s0, $t1            # $t1 = base + (i×4) = عنوان arr[i]
    sw $v0, 0($t1)               # خزّن الرقم في المصفوفة
                                  # ← C++: arr[i] = v0;

    add $t2, $t2, $v0            # sum += v0
    addi $t0, $t0, 1             # i++
    b input_loop

sum_done:
    # ========================================
    # اطبع المجموع
    # ========================================
    la $a0, sum_msg
    li $v0, 4
    syscall

    move $a0, $t2
    li $v0, 1
    syscall

    li $v0, 10
    syscall
