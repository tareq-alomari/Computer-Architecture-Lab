# ============================================================
# 07b: حساب مجموع المصفوفة
# ============================================================
#
# ✨ نجمع كل أرقام المصفوفة:
#    sum = 0
#    for (i = 0; i < 5; i++)
#        sum += arr[i]
#
#    sll: i × 4
#    lw:  اقرأ من المصفوفة
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    arr:    .word 10, 20, 30, 40, 50   # مصفوفة جاهزة (5 أرقام)
    sum_msg: .asciiz "Sum = "
    newline: .asciiz "\n"

.text
main:
    la $s0, arr              # $s0 = base = عنوان أول عنصر
    li $t0, 0                # $t0 = i = 0
    li $t2, 0                # $t2 = sum = 0

sum_loop:
    # ------------------------------
    # شرط: i < 5 ?
    # ------------------------------
    bge $t0, 5, done         # if i >= 5 → اخرج

    # ------------------------------
    # sum += arr[i]
    #   1) احسب i × 4
    #   2) base + (i × 4) = عنوان arr[i]
    #   3) lw: اقرأ القيمة من هذا العنوان
    #   4) اجمعها مع sum
    # ------------------------------
    sll $t1, $t0, 2          # $t1 = i × 4
    add $t1, $s0, $t1        # $t1 = عنوان arr[i]
    lw $t3, 0($t1)           # $t3 = arr[i]   (اقرأ من RAM)
    add $t2, $t2, $t3        # sum += arr[i]

    addi $t0, $t0, 1         # i++
    b sum_loop

done:
    la $a0, sum_msg
    li $v0, 4
    syscall

    move $a0, $t2
    li $v0, 1
    syscall                  # يظهر: 150

    li $v0, 10
    syscall
