# ============================================================
# 10a: إدخال درجات الطلاب — Input Grades
# ============================================================
#
# ✨ نطبق كل ما تعلمناه:
#   .space   ← حجز مصفوفة
#   sw       ← تخزين في RAM
#   sll + add ← الوصول إلى arr[i]
#   bge, addi, b ← حلقات التكرار
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    # مصفوفة تتسع لـ 50 درجة
    grades: .space 200        # 50 × 4 = 200 بايت

    msg_n:  .asciiz "Number of students: "
    msg_g:  .asciiz "Grade: "

.text
main:
    # ------------------------------
    # 1) اسأل: كم عدد الطلاب؟
    # ------------------------------
    la $a0, msg_n
    li $v0, 4
    syscall

    li $v0, 5
    syscall

    # ------------------------------
    # 2) اقرأ درجات كل طالب
    # ------------------------------
    move $s1, $v0            # $s1 = n (عدد الطلاب)
    la $s0, grades           # $s0 = عنوان أول عنصر
    li $t0, 0                # $t0 = i = 0

input_loop:
    bge $t0, $s1, done

    la $a0, msg_g
    li $v0, 4
    syscall

    li $v0, 5
    syscall                  # $v0 = الدرجة

    sll $t1, $t0, 2          # $t1 = i × 4
    add $t1, $s0, $t1        # $t1 = عنوان grades[i]
    sw $v0, 0($t1)           # grades[i] = الدرجة

    addi $t0, $t0, 1         # i++
    b input_loop

done:
    li $v0, 10
    syscall
