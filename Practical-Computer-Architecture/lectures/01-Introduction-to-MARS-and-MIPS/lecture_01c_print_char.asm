# ============================================================
# 01c: اطبع حرفاً — Print Character
# ============================================================
#
# ✨ syscall 11 تطبع حرفاً واحداً
#    الحرف = رقم في ASCII
#    'A' = 65, 'a' = 97, '0' = 48
# ============================================================

.data
    msg: .asciiz "Letters: "

.text
main:
    la $a0, msg
    li $v0, 4
    syscall

    li $a0, 65         # 'A'
    li $v0, 11         # syscall 11 = اطبع حرفاً
    syscall            # يظهر: A

    li $a0, 66         # 'B'
    syscall            # يظهر: B

    li $a0, 67         # 'C'
    syscall            # يظهر: C

    li $v0, 10
    syscall
