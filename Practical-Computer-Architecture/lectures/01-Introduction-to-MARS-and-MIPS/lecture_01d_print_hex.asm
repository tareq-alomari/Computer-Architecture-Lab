# ============================================================
# 01d: اطبع بصيغة Hex — Print Hexadecimal
# ============================================================
#
# ✨ syscall 34 تطبع رقم بصيغة hex
#    مفيدة للمصفوفات والعناوين
# ============================================================

.data
    msg: .asciiz "255 in hex = 0x"

.text
main:
    la $a0, msg
    li $v0, 4
    syscall

    li $a0, 255        # الرقم
    li $v0, 34         # syscall 34 = اطبع hex
    syscall            # يظهر: 0x000000FF

    li $v0, 10
    syscall
