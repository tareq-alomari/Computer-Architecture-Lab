# ============================================================
# المحاضرة الأولى: أول برنامج MIPS — اطبع "Hello World!"
# ============================================================
#
# ----------------------------------
# الأوامر الجديدة في هذا الملف:
#   .data      → قسم البيانات (RAM)
#   .text      → قسم الكود (تعليمات CPU)
#   main:      → نقطة بداية البرنامج
#   la $a0, x  → ضع عنوان x في $a0
#   li $v0, n  → ضع الرقم n في $v0
#   syscall    → اطلب خدمة من نظام التشغيل
#   .asciiz    → احجز نصاً في RAM + \0
# ----------------------------------

.data
    msg: .asciiz "Hello World!\n"     # عرّف النص "Hello World!\n" في RAM

.text
main:
    # ---------- اطبع النص ----------
    la $a0, msg          # $a0 = عنوان msg   (C++: a0 = &msg;)
    li $v0, 4            # $v0 = 4           (C++: اختر خدمة "اطبع نص")
    syscall              # نفّذ: اطبع النص الذي في $a0

    # ---------- اخروج ----------
    li $v0, 10           # $v0 = 10          (C++: return 0;)
    syscall              # أنهِ البرنامج
