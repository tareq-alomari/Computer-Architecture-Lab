# ============================================================
# 01: أول برنامج MIPS — اطبع "Hello World!"
# ============================================================
#
# ✨ أول برنامج لك في MIPS!
#    يطبع جملة "Hello World!" على الشاشة
#
# أوامر جديدة:
#   .data     → قسم البيانات (RAM)
#   .text     → قسم الكود (تعليمات CPU)
#   main:     → نقطة بداية البرنامج
#   la $a0, x  → ضع عنوان x في $a0
#   li $v0, n  → ضع الرقم n في $v0
#   syscall   → اطلب خدمة من نظام التشغيل
#   .asciiz   → احجز نصاً في RAM + \0 في النهاية
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    # ------ قسم البيانات (RAM) ------
    # هنا نخزّن المتغيرات والنصوص

    msg: .asciiz "Hello World!\n"
    # msg: اسم المتغير (label)
    # .asciiz: يخزّن نصاً في RAM مع \0 في النهاية
    # "Hello World!\n": النص نفسه
    # ← C++: char msg[] = "Hello World!\n";

.text
main:
    # ------ قسم الكود (التعليمات) ------
    # main: نقطة البداية (زي int main() في C++)

    # ------------------------------
    # 1) اطبع النص على الشاشة
    # ------------------------------
    la $a0, msg      # $a0 = عنوان msg (أين يوجد النص في RAM)
                      # ← C++: a0 = &msg;

    li $v0, 4        # $v0 = 4    (رقم خدمة "اطبع نص")
                      # syscall 4: يطبع أي نص عنوانه في $a0

    syscall          # نفّذ! اطبع النص
                      # يظهر: Hello World!

    # ------------------------------
    # 2) اخروج من البرنامج
    # ------------------------------
    li $v0, 10       # $v0 = 10   (رقم خدمة "خروج")
                      # ← C++: return 0;

    syscall          # أنهِ البرنامج
