# ============================================================
# مثال ب: اقرأ رقماً من المستخدم ثم اطبعه
# ============================================================
#
# ✨ تعلّم كيف تقرأ رقم من المستخدم وتطبعه
#
# أوامر جديدة:
#   move $d, $s  →  $d = $s  (انسخ بين مسجلين)
#   syscall 5    → اقرأ عدداً (النتيجة في $v0)
#   syscall 1    → اطبع عدداً (الرقم في $a0)
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    prompt: .asciiz "Enter a number: "     # "أدخل رقماً"
    out_msg: .asciiz "You entered: "       # "لقد أدخلت: "
    newline: .asciiz "\n"

.text
main:
    # ------------------------------
    # 1) اطبع "Enter a number: "
    # ------------------------------
    la $a0, prompt           # $a0 = عنوان النص
    li $v0, 4                # syscall 4 = اطبع نصاً
    syscall                  # تظهر الرسالة

    # ------------------------------
    # 2) اقرأ رقماً من المستخدم
    # ------------------------------
    li $v0, 5                # syscall 5 = اقرأ عدداً
    syscall                  # المستخدم يدخل رقماً
                              # $v0 = الرقم المدخل

    move $t0, $v0            # $t0 = $v0
                              # انسخ الرقم من $v0 إلى $t0
                              # (عشان نحفظه)

    # ------------------------------
    # 3) اطبع "You entered: "
    # ------------------------------
    la $a0, out_msg
    li $v0, 4
    syscall

    # ------------------------------
    # 4) اطبع الرقم
    # ------------------------------
    move $a0, $t0            # $a0 = الرقم
    li $v0, 1                # syscall 1 = اطبع عدداً
    syscall                  # يظهر الرقم

    # ------------------------------
    # 5) خروج
    # ------------------------------
    li $v0, 10
    syscall
