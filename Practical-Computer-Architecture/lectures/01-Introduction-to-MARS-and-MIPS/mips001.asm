# ============================================================
# مثال ب: اقرأ رقماً من المستخدم ثم اطبعه
# ============================================================
#
# ----------------------------------
# الأوامر الجديدة هنا:
#   move $d, $s  → $d = $s  (انسخ قيمة بين مسجلين)
#   syscall 5    → اقرأ عدداً صحيحاً (النتيجة في $v0)
#   syscall 1    → اطبع عدداً صحيحاً (الرقم في $a0)
# ----------------------------------

.data
    prompt: .asciiz "Enter a number: "    # نص يطلب الإدخال
    out_msg: .asciiz "You entered: "      # نص النتيجة
    newline: .asciiz "\n"

.text
main:
    # ---------- اطبع "Enter a number: " ----------
    la $a0, prompt        # $a0 = عنوان prompt
    li $v0, 4             # syscall 4 = اطبع نصاً
    syscall

    # ---------- اقرأ رقماً من المستخدم ----------
    li $v0, 5             # syscall 5 = اقرأ عدداً
    syscall               # $v0 = الرقم الذي كتبه المستخدم
    move $t0, $v0         # $t0 = $v0  (احفظ الرقم مؤقتاً)

    # ---------- اطبع "You entered: " ----------
    la $a0, out_msg
    li $v0, 4
    syscall

    # ---------- اطبع الرقم ----------
    move $a0, $t0         # $a0 = $t0  (جهّز الرقم للطباعة)
    li $v0, 1             # syscall 1 = اطبع عدداً
    syscall

    # ---------- اخروج ----------
    li $v0, 10
    syscall
