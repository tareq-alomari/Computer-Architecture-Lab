# ============================================================
# 09b: دالة مضروب — FACTORIAL (باستخدام المكدس)
# ============================================================
#
# ✨ المضروب: 5! = 5 × 4 × 3 × 2 × 1 = 120
#
#   الدالة تستدعي نفسها (recursion)
#   نحتاج $sp (المكدس) عشان نحفظ القيم
#
#   $sp = Stack Pointer (مؤشر المكدس)
#   SW = احفظ على المكدس
#   LW = استرجع من المكدس
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    msg_fact: .asciiz "5! = "
    newline:  .asciiz "\n"

.text
main:
    la $a0, msg_fact
    li $v0, 4
    syscall

    li $a0, 5                # نريد: 5!
    jal factorial            # استدعِ الدالة

    move $a0, $v0            # $v0 = النتيجة (120)
    li $v0, 1
    syscall                  # يظهر: 120

    li $v0, 10
    syscall

# ========================================
# الدالة: factorial(n) ← ترجع n!
# الصيغة: if n <= 1 → return 1
#          else → return n * factorial(n-1)
# ========================================
factorial:
    # ---- جهّز المكدس ----
    addi $sp, $sp, -8        # $sp = $sp - 8   (احجز مسافتين في المكدس)
    sw $ra, 0($sp)           # احفظ $ra في أول خانة (عنوان الرجوع)
    sw $a0, 4($sp)           # احفظ $a0 في ثاني خانة (قيمة n)

    # ---- إذا n <= 1 → return 1 ----
    li $t0, 1
    ble $a0, $t0, base_case

    # ---- n * factorial(n-1) ----
    addi $a0, $a0, -1        # n = n - 1
    jal factorial            # استدعِ factorial(n-1)
    lw $a0, 4($sp)           # استرجع قيمة n الأصلية من المكدس
    mul $v0, $a0, $v0        # $v0 = n * factorial(n-1)
    b return_fact

base_case:
    li $v0, 1                # return 1

return_fact:
    lw $ra, 0($sp)           # استرجع $ra من المكدس
    addi $sp, $sp, 8         # حرّر المكدس (أرجع $sp لمكانه)
    jr $ra                   # ارجع إلى main
