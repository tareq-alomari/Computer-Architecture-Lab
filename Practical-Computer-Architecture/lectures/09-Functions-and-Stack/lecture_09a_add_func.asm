# ============================================================
# 09a: دالة جمع — JAL / JR / $RA
# ============================================================
#
# ✨ أول دالة لك في MIPS!
#    مثل C++: int add(int a, int b) { return a + b; }
#
#   JAL = Jump And Link ← استدعِ دالة
#         (يحفظ عنوان الرجوع في $ra ويقفز)
#   JR $ra = Jump Register ← ارجع من الدالة
#
#   نمرّر المعاملات عبر: $a0, $a1
#   نسترجع النتيجة عبر:  $v0
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    msg_add: .asciiz "5 + 3 = "
    newline: .asciiz "\n"

.text
main:
    # ------------------------------
    # 1) اطبع "5 + 3 = "
    # ------------------------------
    la $a0, msg_add
    li $v0, 4
    syscall

    # ------------------------------
    # 2) جهّز المعاملات واستدعِ الدالة
    # ------------------------------
    li $a0, 5                # $a0 = 5   (المعامل الأول)
    li $a1, 3                # $a1 = 3   (المعامل الثاني)

    jal add_func             # استدعِ الدالة add_func
                              # 1) احفظ عنوان الرجوع في $ra
                              # 2) اقفز إلى add_func
                              # ← C++: result = add(5, 3);

    # ------------------------------
    # 3) $v0 يحتوي على النتيجة (8)
    # ------------------------------
    move $a0, $v0            # $a0 = 8
    li $v0, 1
    syscall                  # يظهر: 8

    li $v0, 10
    syscall

# ========================================
# الدالة: add_func(a, b) ← ترجع a + b
# ========================================
add_func:
    add $v0, $a0, $a1       # $v0 = $a0 + $a1   ← C++: return a + b;
    jr $ra                  # ارجع إلى main (عنوان الرجوع في $ra)
