# ============================================================
# 04a: هل الرقم زوجي أم فردي؟ (Even / Odd)
# ============================================================
#
# ✨ الفكرة بسيطة:
#   - أي رقم زوجي: LSB = 0  (مثال: 6 = 110)
#   - أي رقم فردي: LSB = 1  (مثال: 5 = 101)
#   نستخدم: ANDI + BEQZ
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    prompt: .asciiz "Enter a number: "   # اسأل المستخدم
    even:   .asciiz "Even\n"             # "زوجي"
    odd:    .asciiz "Odd\n"              # "فردي"

.text
main:
    # ------------------------------
    # 1) اسأل المستخدم: أدخل رقم
    # ------------------------------
    la $a0, prompt     # $a0 = عنوان النص "Enter a number: "
    li $v0, 4          # $v0 = 4 ← syscall اطبع نص
    syscall            # تظهر الرسالة

    li $v0, 5          # $v0 = 5 ← syscall اقرأ رقماً
    syscall            # المستخدم يدخل رقم
    move $t0, $v0      # $t0 = الرقم اللي أدخله المستخدم

    # ------------------------------
    # 2) اختبر: هل الرقم زوجي أم فردي؟
    #    الفكرة: (رقم & 1) == 0 ← زوجي
    # ------------------------------
    andi $t1, $t0, 1   # $t1 = $t0 & 1
                        # نأخذ أقل بت (LSB) فقط
                        # إذا LSB = 0 → زوجي
                        # إذا LSB = 1 → فردي

    beqz $t1, print_even  # if $t1 == 0 → اذهب إلى print_even
                           # يعني: إذا كان زوجياً → اطبع "Even"

    # --- هنا نصل إذا was الرقم فردياً ---
    la $a0, odd        # $a0 = عنوان "Odd\n"
    li $v0, 4
    syscall            # اطبع "Odd"
    b done             # اذهب إلى done (نتخطى print_even)

print_even:
    # --- هنا نصل إذا كان الرقم زوجياً ---
    la $a0, even       # $a0 = عنوان "Even\n"
    li $v0, 4
    syscall            # اطبع "Even"

done:
    li $v0, 10         # $v0 = 10 ← syscall خروج
    syscall
