# ============================================================
# 08a: حساب طول النص — STRLEN
# ============================================================
#
# ✨ الفكرة: كل نص في MIPS ينتهي بـ \0 (null)
#    نمشي على الحروف واحد واحد
#    نوصل لـ \0 → نوقف
#    عدد الحروف = طول النص
#
#    LB = Load Byte (نقرأ حرف واحد)
#    BEQZ = إذا صادفنا 0 → انتهى النص
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    str: .asciiz "hello"         # "hello" + \0  (6 بايت في RAM)
    msg_len: .asciiz "Length = "
    newline: .asciiz "\n"

.text
main:
    # ------------------------------
    # 1) اطبع "Length = "
    # ------------------------------
    la $a0, msg_len
    li $v0, 4
    syscall

    # ------------------------------
    # 2) جهّز:
    #    $t0 = عنوان أول حرف في النص
    #    $t1 = عداد الطول (يبدأ من 0)
    # ------------------------------
    la $t0, str              # $t0 = عنوان أول حرف 'h'
    li $t1, 0                # $t1 = length = 0

len_loop:
    # ------------------------------
    # 3) اقرأ الحرف الحالي
    # ------------------------------
    lb $t2, 0($t0)           # $t2 = الحرف اللي في العنوان $t0
                              # أول مرة: $t2 = 'h' = 104

    # ------------------------------
    # 4) إذا الحرف = 0 (null) → انتهينا
    # ------------------------------
    beqz $t2, done_len       # if $t2 == 0 → اذهب إلى done_len

    # ------------------------------
    # 5) length++  و  انتقل للحرف التالي
    # ------------------------------
    addi $t1, $t1, 1         # length++ (زد العداد)
    addi $t0, $t0, 1         # $t0++   (انتقل للعنوان التالي)

    b len_loop               # كرّر

done_len:
    # ------------------------------
    # 6) اطبع النتيجة
    # ------------------------------
    move $a0, $t1            # $a0 = length (5)
    li $v0, 1
    syscall                  # يظهر: 5

    li $v0, 10
    syscall
