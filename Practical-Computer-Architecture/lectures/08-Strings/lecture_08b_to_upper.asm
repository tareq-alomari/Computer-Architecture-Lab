# ============================================================
# 08b: تحويل الحروف الصغيرة → كبيرة  (TO UPPER)
# ============================================================
#
# ✨ الفكرة: الفرق بين 'a' و 'A' = 32
#    'a' = 97    'A' = 65     الفرق = 32
#    نحول: حرف صغير - 32 = حرف كبير
#
#    LB = Load Byte  (نقرأ حرفاً)
#    SB = Store Byte (نكتب حرفاً)
#    BLT = Branch if Less Than
#    BGT = Branch if Greater Than
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    str: .asciiz "hello"         # "hello" في RAM
    msg_up:  .asciiz "Uppercase: "
    newline: .asciiz "\n"

.text
main:
    la $a0, msg_up
    li $v0, 4
    syscall

    # ------------------------------
    # 1) $t0 = عنوان أول حرف
    # ------------------------------
    la $t0, str              # $t0 يشير إلى 'h'

upper_loop:
    # ------------------------------
    # 2) اقرأ الحرف الحالي
    # ------------------------------
    lb $t2, 0($t0)           # $t2 = الحرف (مثل 'h' = 104)

    # ------------------------------
    # 3) إذا null → انتهى النص
    # ------------------------------
    beqz $t2, done_upper

    # ------------------------------
    # 4) تحقق: هل الحرف بين 'a' (97) و 'z' (122)؟
    # ------------------------------
    li $t3, 97               # $t3 = 'a' = 97
    blt $t2, $t3, skip       # if $t2 < 97 → مش حرف صغير → تجاوز

    li $t3, 122              # $t3 = 'z' = 122
    bgt $t2, $t3, skip       # if $t2 > 122 → مش حرف صغير → تجاوز

    # ------------------------------
    # 5) حوّل إلى كبير: c - 32
    # ------------------------------
    addi $t2, $t2, -32       # 'h'(104) - 32 = 'H'(72)
    sb $t2, 0($t0)           # خزّن الحرف الكبير مكان الصغير في RAM

skip:
    addi $t0, $t0, 1         # انتقل للحرف التالي
    b upper_loop

done_upper:
    # ------------------------------
    # 6) اطبع النص بعد التحويل
    # ------------------------------
    la $a0, str
    li $v0, 4
    syscall                  # يظهر: HELLO

    li $v0, 10
    syscall
