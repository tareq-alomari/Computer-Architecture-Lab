# ============================================================
# 03b: إزاحة البتات — SLL / SRL
# ============================================================
#
# ✨ تعلّم إزاحة البتات:
#   SLL: Shift Left Logical  ← إزاحة لليسار (ضرب × 2^n)
#   SRL: Shift Right Logical ← إزاحة لليمين (قسمة ÷ 2^n)
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    msg_sll: .asciiz "a << 8   = 0x"
    msg_srl: .asciiz "a >> 8   = 0x"
    newline: .asciiz "\n"

.text
main:
    li $t0, 0x12345678   # a = 0x12345678

    # ------------------------------
    # SLL: a << 8
    #    كل إزاحة لليسار = ضرب × 2
    #    << 8 = ضرب × 256
    # ------------------------------
    la $a0, msg_sll
    li $v0, 4
    syscall

    sll $t4, $t0, 8      # $t4 = $t0 << 8
                          # كل البتات تتحرك 8 خانات لليسار
                          # المعنى: 0x12345678 → 0x34567800

    move $a0, $t4
    li $v0, 34            # اطبع hex
    syscall

    la $a0, newline
    li $v0, 4
    syscall

    # ------------------------------
    # SRL: a >> 8
    #    كل إزاحة لليمين = قسمة ÷ 2
    #    >> 8 = قسمة ÷ 256
    # ------------------------------
    la $a0, msg_srl
    li $v0, 4
    syscall

    srl $t5, $t0, 8      # $t5 = $t0 >> 8
                          # كل البتات تتحرك 8 خانات لليمين
                          # المعنى: 0x12345678 → 0x00123456

    move $a0, $t5
    li $v0, 34
    syscall

    li $v0, 10
    syscall
