# ============================================================
# 03a: العمليات المنطقية — AND / OR / XOR
# ============================================================
#
# ✨ تعلّم كيف تتعامل مع البتات:
#   AND: 1 & 1 = 1   (إخفاء bits)
#   OR:  0 | 1 = 1   (تشغيل bits)  
#   XOR: 0 ^ 1 = 1   (عكس bits)
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    msg_and: .asciiz "a & 0xFF = 0x"   # نص
    msg_or:  .asciiz "a | 0xFF = 0x"
    msg_xor: .asciiz "a ^ 0xFF = 0x"
    newline: .asciiz "\n"

.text
main:
    # ------------------------------
    # 1) قيمة البداية
    # ------------------------------
    li $t0, 0x12345678   # a = 0x12345678 (رقم كبير بالنظام الـ hex)

    # ------------------------------
    # 2) AND: a & 0xFF
    #    معنى: احتفظ بأول 8 bits فقط
    # ------------------------------
    la $a0, msg_and
    li $v0, 4
    syscall

    andi $t1, $t0, 0xFF   # $t1 = $t0 & 0xFF
                           # 0xFF = 255 = أول 8 bits كلها 1
                           # يحتفظ بـ 0x78 فقط

    move $a0, $t1
    li $v0, 34             # syscall 34 = اطبع بصيغة hex
    syscall

    la $a0, newline
    li $v0, 4
    syscall

    # ------------------------------
    # 3) OR: a | 0xFF
    #    معنى: اجعل أول 8 bits كلها 1
    # ------------------------------
    la $a0, msg_or
    li $v0, 4
    syscall

    ori $t2, $t0, 0xFF     # $t2 = $t0 | 0xFF
                           # يجعل أول 8 bits كلها 1

    move $a0, $t2
    li $v0, 34
    syscall

    la $a0, newline
    li $v0, 4
    syscall

    # ------------------------------
    # 4) XOR: a ^ 0xFF
    #    معنى: اعكس أول 8 bits
    # ------------------------------
    la $a0, msg_xor
    li $v0, 4
    syscall

    xori $t3, $t0, 0xFF     # $t3 = $t0 ^ 0xFF
                            # يعكس أول 8 bits

    move $a0, $t3
    li $v0, 34
    syscall

    li $v0, 10
    syscall
