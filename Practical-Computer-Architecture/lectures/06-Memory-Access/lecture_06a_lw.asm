# ============================================================
# 06a: قراءة من الذاكرة — LW (Load Word)
# ============================================================
#
# ✨ الفرق بين RAM و Register:
#   RAM (الذاكرة):    تخزين دائم، كبير، بطيء
#   Register (مسجل): تخزين مؤقت، صغير، سريع
#
#   LW = Load Word = RAM → Register
#   نقرأ قيمة من RAM ونحطها في مسجل
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    # ---- RAM (الذاكرة) ----
    x: .word 42             # احجز 4 بايت في RAM
                             # الاسم: x    القيمة: 42
                             # ← C++: int x = 42;

    msg_x:  .asciiz "x = "  # نص للطباعة

.text
main:
    # ------------------------------
    # 1) اطبع "x = "
    # ------------------------------
    la $a0, msg_x
    li $v0, 4
    syscall

    # ------------------------------
    # 2) اقرأ x من RAM إلى $t0
    # ------------------------------
    lw $t0, x               # $t0 = x
                             # اذهب إلى RAM، ابحث عن x، خذ قيمتها (42)
                             # ← C++: int t0 = x;

    move $a0, $t0           # $a0 = 42
    li $v0, 1               # اطبع رقماً
    syscall                 # يظهر: 42

    li $v0, 10
    syscall
