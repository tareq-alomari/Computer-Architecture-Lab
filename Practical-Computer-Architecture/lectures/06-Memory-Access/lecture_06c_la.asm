# ============================================================
# 06c: عنوان vs قيمة — LA مقابل LW
# ============================================================
#
# ✨ مهم جداً: الفرق بين:
#   LA = Load Address  ← أعطني عنوان المتغير في RAM
#   LW = Load Word     ← أعطني قيمة المتغير من RAM
#
# مثل في C++:
#   int* p = &x;    ← LA (العنوان)
#   int v = x;      ← LW (القيمة)
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    x: .word 42              # int x = 42;  (في RAM)

    addr_x: .asciiz "Address of x = 0x"
    newline: .asciiz "\n"

.text
main:
    # ------------------------------
    # 1) اطبع نص
    # ------------------------------
    la $a0, addr_x
    li $v0, 4
    syscall

    # ------------------------------
    # 2) LA: خذ عنوان x (أين يوجد x في RAM)
    # ------------------------------
    la $t3, x                # $t3 = عنوان x (رقم كبير = مكان x في RAM)
                              # ← C++: int* t3 = &x;

    move $a0, $t3
    li $v0, 34               # syscall 34 = اطبع بصيغة hex
    syscall                  # يظهر عنوان x (مثل: 0x10010000)

    li $v0, 10
    syscall
