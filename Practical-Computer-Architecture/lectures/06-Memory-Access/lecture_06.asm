# ============================================================
# المحاضرة السادسة: التعامل مع الذاكرة — lw, sw, la
# ============================================================
#
# ----------------------------------
# الأوامر الجديدة:
#   .word n          →  احجز 4 بايت في RAM، القيمة = n
#   lw $t, label     →  اقرأ 4 بايت من RAM إلى المسجل (C++: t = x;)
#   sw $t, label     →  اكتب 4 بايت من المسجل إلى RAM (C++: x = t;)
#   la $t, label     →  ضع عنوان label في المسجل (C++: t = &x;)
#   syscall 34       →  اطبع رقماً بصيغة hex
# ----------------------------------

.data
    x: .word 42                # int x = 42;  (في RAM)
    y: .word 0                 # int y = 0;
    msg_x:  .asciiz "x = "
    msg_y:  .asciiz "y = "
    addr_x: .asciiz "Address of x = 0x"
    newline: .asciiz "\n"

.text
main:
    # ========================================
    # مثال: lw — اقرأ من RAM إلى مسجل
    # C++: int t0 = x;
    # ========================================
    la $a0, msg_x
    li $v0, 4
    syscall
    lw $t0, x                   # $t0 = x   (اقرأ قيمة x من RAM)
    move $a0, $t0
    li $v0, 1
    syscall
    la $a0, newline
    li $v0, 4
    syscall

    # ========================================
    # مثال: sw — اكتب من مسجل إلى RAM
    # C++: int t1 = 99; y = t1;
    # ========================================
    li $t1, 99                  # $t1 = 99
    sw $t1, y                   # y = $t1   (اكتب 99 في RAM)
    la $a0, msg_y
    li $v0, 4
    syscall
    lw $t2, y                   # اقرأ y من RAM للتحقق
    move $a0, $t2
    li $v0, 1
    syscall
    la $a0, newline
    li $v0, 4
    syscall

    # ========================================
    # مثال: la مقابل lw — الفرق بين العنوان والقيمة
    # C++: t3 = &x;   (la تعطي العنوان)
    #      t0 = x;    (lw تعطي القيمة)
    # ========================================
    la $a0, addr_x
    li $v0, 4
    syscall
    la $t3, x                   # $t3 = عنوان x (C++: t3 = &x;)
    move $a0, $t3
    li $v0, 34                  # اطبع العنوان كـ hex
    syscall
    la $a0, newline
    li $v0, 4
    syscall

    # ---------- اخروج ----------
    li $v0, 10
    syscall
