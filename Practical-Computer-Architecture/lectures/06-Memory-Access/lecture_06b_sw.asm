# ============================================================
# 06b: كتابة إلى الذاكرة — SW (Store Word)
# ============================================================
#
# ✨ SW = Store Word = Register → RAM
#   نأخذ قيمة من مسجل ونخزّنها في الذاكرة
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    # ---- RAM (الذاكرة) ----
    y: .word 0              # احجز 4 بايت في RAM
                             # الاسم: y    القيمة: 0 (في البداية)
                             # ← C++: int y = 0;

    msg_y:  .asciiz "y = "
    newline: .asciiz "\n"

.text
main:
    # ------------------------------
    # 1) ضع 99 في مسجل $t1
    # ------------------------------
    li $t1, 99              # $t1 = 99   ← هذا في المسجل (سريع)

    # ------------------------------
    # 2) خزّن 99 من $t1 إلى RAM (في y)
    # ------------------------------
    sw $t1, y               # y = $t1
                             # خذ قيمة $t1 (= 99) واحفظها في RAM في y
                             # ← C++: y = t1;

    # ------------------------------
    # 3) اقرأ y من RAM واطبعها (نتأكد أنها 99)
    # ------------------------------
    la $a0, msg_y
    li $v0, 4
    syscall

    lw $t2, y               # $t2 = y   (نقرأ y من RAM)
    move $a0, $t2
    li $v0, 1
    syscall                 # يظهر: 99

    li $v0, 10
    syscall
