# ============================================================
# 05b: حلقة while — مجموع 1+2+3+...+N
# ============================================================
#
# ✨ الفكرة: نجمع أرقام من 1 إلى N
#    مثل: sum = 0; i = 1;
#          while (i <= N) { sum += i; i++; }
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    prompt:  .asciiz "Enter N: "     # اسأل "أدخل رقم"
    sum_msg: .asciiz "Sum = "        # "المجموع = "
    newline: .asciiz "\n"

.text
main:
    # ------------------------------
    # 1) اسأل المستخدم عن N
    # ------------------------------
    la $a0, prompt
    li $v0, 4
    syscall

    li $v0, 5
    syscall
    move $t1, $v0            # $t1 = N (الرقم اللي أدخله المستخدم)

    # ------------------------------
    # 2) البداية: i = 1, sum = 0
    # ------------------------------
    li $t2, 1                # $t2 = i   (العداد)
    li $t3, 0                # $t3 = sum (المجموع. يبدأ بـ 0)

sum_loop:
    # ------------------------------
    # 3) شرط: i <= N ?
    #    نعكس: إذا i > N → اخرج
    # ------------------------------
    bgt $t2, $t1, done_sum   # if $t2 > $t1 → اذهب إلى done_sum

    # ------------------------------
    # 4) sum = sum + i
    # ------------------------------
    add $t3, $t3, $t2        # $t3 = $t3 + $t2   ← C++: sum += i;

    # ------------------------------
    # 5) i++
    # ------------------------------
    addi $t2, $t2, 1         # $t2++   ← C++: i++;

    b sum_loop               # ارجع إلى sum_loop

done_sum:
    # ------------------------------
    # 6) اطبع النتيجة
    # ------------------------------
    la $a0, sum_msg
    li $v0, 4
    syscall

    move $a0, $t3            # $a0 = sum
    li $v0, 1
    syscall                  # يظهر المجموع

    li $v0, 10
    syscall
