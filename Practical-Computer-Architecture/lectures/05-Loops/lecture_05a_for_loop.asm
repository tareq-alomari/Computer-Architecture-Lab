# ============================================================
# 05a: حلقة for — اطبع الأعداد 1 2 3 ... 10
# ============================================================
#
# ✨ الفكرة: نستخدم عداد (counter) يزيد كل مرة
#    مثل: for (int i = 1; i <= 10; i++)
#
# في MIPS نستخدم:
#   li   ← نضع قيمة البداية
#   bgt  ← نختبر شرط الخروج
#   addi ← نزيد العداد
#   b    ← نرجع إلى بداية الحلقة
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    space:   .asciiz " "      # مسافة
    newline: .asciiz "\n"

.text
main:
    # ------------------------------
    # 1) البداية: i = 1
    # ------------------------------
    li $t0, 1              # $t0 = 1   ← هذا هو العداد i

print_loop:
    # ------------------------------
    # 2) شرط الاستمرار: i <= 10؟
    #    في MIPS نعكس الشرط:
    #    "إذا i > 10 → اخرج"
    # ------------------------------
    bgt $t0, 10, done_print  # if $t0 > 10 → اذهب إلى done_print
                              # يعني: لما i يوصل 11، نوقف

    # ------------------------------
    # 3) اطبع i
    # ------------------------------
    move $a0, $t0        # $a0 = i
    li $v0, 1            # اطبع رقماً
    syscall              # يظهر: 1 2 3 ...

    la $a0, space        # اطبع مسافة " "
    li $v0, 4
    syscall

    # ------------------------------
    # 4) i++   (زد العداد)
    # ------------------------------
    addi $t0, $t0, 1     # $t0 = $t0 + 1   ← i++

    # ------------------------------
    # 5) ارجع إلى بداية الحلقة
    # ------------------------------
    b print_loop         # ارجع إلى print_loop

done_print:
    la $a0, newline
    li $v0, 4
    syscall

    li $v0, 10
    syscall
