# ============================================================
# 02: العمليات الحسابية — جمع، طرح، ضرب، قسمة
# ============================================================
#
# ✨ كل العمليات الحسابية في ملف واحد (كمرجع كامل)
#    للنسخ المبسّطة، راجع:
#      lecture_02a_add_sub.asm  ← جمع وطرح فقط
#      lecture_02b_mul_div.asm  ← ضرب وقسمة فقط
#
# أوامر جديدة:
#   add  $d, $a, $b  →  $d = $a + $b  (جمع)
#   sub  $d, $a, $b  →  $d = $a - $b  (طرح)
#   mul  $d, $a, $b  →  $d = $a * $b  (ضرب)
#   div  $a, $b      →  $a ÷ $b       (قسمة)
#   mflo $d          →  $d = LO       (ناتج القسمة)
#   mfhi $d          →  $d = HI       (باقي القسمة)
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    msg_add: .asciiz "a + b = "
    msg_sub: .asciiz "a - b = "
    msg_mul: .asciiz "a * b = "
    msg_div: .asciiz "a / b = "
    msg_rem: .asciiz "a % b = "
    newline: .asciiz "\n"

.text
main:
    # ------------------------------
    # 1) نضع قيمتين
    # ------------------------------
    li $t0, 10               # $t0 = 10   ← int a = 10;
    li $t1, 3                # $t1 = 3    ← int b = 3;

    # ------------------------------
    # 2) a + b  (جمع)
    # ------------------------------
    la $a0, msg_add
    li $v0, 4
    syscall

    add $t2, $t0, $t1        # $t2 = $t0 + $t1 = 10 + 3 = 13

    move $a0, $t2
    li $v0, 1
    syscall                  # يظهر: 13

    la $a0, newline
    li $v0, 4
    syscall

    # ------------------------------
    # 3) a - b  (طرح)
    # ------------------------------
    la $a0, msg_sub
    li $v0, 4
    syscall

    sub $t3, $t0, $t1        # $t3 = $t0 - $t1 = 10 - 3 = 7

    move $a0, $t3
    li $v0, 1
    syscall                  # يظهر: 7
    la $a0, newline
    li $v0, 4
    syscall

    # ------------------------------
    # 4) a * b  (ضرب)
    # ------------------------------
    la $a0, msg_mul
    li $v0, 4
    syscall

    mul $t4, $t0, $t1        # $t4 = $t0 * $t1 = 10 * 3 = 30

    move $a0, $t4
    li $v0, 1
    syscall                  # يظهر: 30
    la $a0, newline
    li $v0, 4
    syscall

    # ------------------------------
    # 5) a / b  (ناتج القسمة)
    #    div: LO = ناتج, HI = باقي
    # ------------------------------
    la $a0, msg_div
    li $v0, 4
    syscall

    div $t0, $t1             # 10 ÷ 3  (LO = 3, HI = 1)
    mflo $t5                 # $t5 = LO = 3  (الناتج)

    move $a0, $t5
    li $v0, 1
    syscall                  # يظهر: 3
    la $a0, newline
    li $v0, 4
    syscall

    # ------------------------------
    # 6) a % b  (باقي القسمة)
    # ------------------------------
    la $a0, msg_rem
    li $v0, 4
    syscall

    mfhi $t6                 # $t6 = HI = 1  (الباقي)

    move $a0, $t6
    li $v0, 1
    syscall                  # يظهر: 1

    # ------------------------------
    # 7) خروج
    # ------------------------------
    li $v0, 10
    syscall
