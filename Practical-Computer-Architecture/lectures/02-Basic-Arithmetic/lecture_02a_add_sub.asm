# ============================================================
# 02a: الجمع والطرح — ADD / SUB
# ============================================================
# 
# ✨ هذا البرنامج يعلّمك عمليتين:
#   الأولى:  الجمع  (ADD)   ←  a + b
#   الثانية: الطرح  (SUB)   ←  a - b
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    # .data = قسم البيانات (مثل RAM)
    # هنا نخزّن النصوص والرسائل

    msg_add: .asciiz "a + b = "      # نص: "a + b = "
    msg_sub: .asciiz "a - b = "      # نص: "a - b = "
    newline: .asciiz "\n"            # سطر جديد

.text
main:
    # .text = قسم الكود (التعليمات)
    # main: = نقطة البداية

    # ------------------------------
    # 1) نضع قيمتين في مسجلين
    # ------------------------------
    li $t0, 10       # $t0 = 10      ← في C++: int a = 10;
    li $t1, 3        # $t1 = 3       ← في C++: int b = 3;

    # ------------------------------
    # 2) نطبع "a + b = " (نص)
    # ------------------------------
    la $a0, msg_add  # $a0 = عنوان النص msg_add
    li $v0, 4        # $v0 = 4       ← syscall 4 = اطبع نصاً
    syscall          # نفّذ الطباعة

    # ------------------------------
    # 3) نجمع: t2 = t0 + t1
    # ------------------------------
    add $t2, $t0, $t1   # $t2 = $t0 + $t1    ← C++: t2 = a + b;

    move $a0, $t2    # $a0 = قيمة t2 (الرقم 13)
    li $v0, 1        # $v0 = 1       ← syscall 1 = اطبع رقماً
    syscall          # نفّذ الطباعة ← يظهر: 13

    # سطر جديد
    la $a0, newline
    li $v0, 4
    syscall

    # ------------------------------
    # 4) نطرح: t3 = t0 - t1
    # ------------------------------
    la $a0, msg_sub  # اطبع "a - b = "
    li $v0, 4
    syscall

    sub $t3, $t0, $t1   # $t3 = $t0 - $t1   ← C++: t3 = a - b;

    move $a0, $t3    # $a0 = قيمة t3 (الرقم 7)
    li $v0, 1        # اطبع الرقم
    syscall          # يظهر: 7

    # ------------------------------
    # 5) خروج من البرنامج
    # ------------------------------
    li $v0, 10       # $v0 = 10    ← syscall 10 = اخروج
    syscall          # أنهِ البرنامج
