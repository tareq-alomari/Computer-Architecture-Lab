# ============================================================
# 02b: الضرب والقسمة — MUL / DIV / MFLO / MFHI
# ============================================================
# 
# ✨ هذا البرنامج يعلّمك:
#   الضرب:  MUL  ←  a * b
#   القسمة: DIV  ←  a / b  (ناتج + باقٍ)
#
# كل سطر له شرح بالعربي 👇
# ============================================================

.data
    msg_mul: .asciiz "a * b = "      # نص: "a * b = "
    msg_div: .asciiz "a / b = "      # نص: "a / b = "
    msg_rem: .asciiz "a % b = "      # نص: "a % b = "
    newline: .asciiz "\n"

.text
main:
    # ------------------------------
    # 1) نضع قيمتين
    # ------------------------------
    li $t0, 10       # a = 10
    li $t1, 3        # b = 3

    # ------------------------------
    # 2) ضرب: t4 = t0 * t1
    # ------------------------------
    la $a0, msg_mul  # اطبع "a * b = "
    li $v0, 4
    syscall

    mul $t4, $t0, $t1  # $t4 = $t0 * $t1   ← C++: t4 = a * b;
                       # 10 × 3 = 30

    move $a0, $t4
    li $v0, 1
    syscall           # يظهر: 30

    la $a0, newline
    li $v0, 4
    syscall

    # ------------------------------
    # 3) قسمة: ناتج a / b
    # ------------------------------
    la $a0, msg_div  # اطبع "a / b = "
    li $v0, 4
    syscall

    div $t0, $t1     # $t0 ÷ $t1        ← 10 ÷ 3
                     # DIV يضع:
                     #   LO = ناتج القسمة (10 / 3 = 3)
                     #   HI = باقي القسمة (10 % 3 = 1)

    mflo $t5         # $t5 = LO         ← ناتج القسمة: 3

    move $a0, $t5
    li $v0, 1
    syscall           # يظهر: 3

    la $a0, newline
    li $v0, 4
    syscall

    # ------------------------------
    # 4) باقي القسمة: a % b
    # ------------------------------
    la $a0, msg_rem  # اطبع "a % b = "
    li $v0, 4
    syscall

    mfhi $t6         # $t6 = HI         ← باقي القسمة: 1

    move $a0, $t6
    li $v0, 1
    syscall           # يظهر: 1

    # ------------------------------
    # 5) خروج
    # ------------------------------
    li $v0, 10
    syscall
