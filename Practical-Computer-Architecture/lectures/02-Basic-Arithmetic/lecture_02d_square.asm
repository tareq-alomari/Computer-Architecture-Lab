# ============================================================
# 02d: تربيع رقم — Square (n × n)
# ============================================================
#
# ✨ المربع = n × n
#    مثلاً: 5 × 5 = 25
# ============================================================

.data
    msg: .asciiz "5^2 = "

.text
main:
    li $t0, 5

    mul $t1, $t0, $t0      # t1 = 5 × 5 = 25

    la $a0, msg
    li $v0, 4
    syscall

    move $a0, $t1
    li $v0, 1
    syscall                # يظهر: 25

    li $v0, 10
    syscall
